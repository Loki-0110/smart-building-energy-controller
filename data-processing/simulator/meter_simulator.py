
import random
from datetime import datetime, timedelta
from decimal import Decimal, InvalidOperation
from typing import Any
from zoneinfo import ZoneInfo

from config.settings import (
    READINGS_PER_BUILDING,
    SIMULATOR_SOURCE_NAME
)

INDIA_TIMEZONE = ZoneInfo("Asia/Kolkata")

# Demand simulation configuration
NORMAL_MIN_KW = 90.0
NORMAL_MAX_KW = 150.0
PEAK_TARGET_KW = 200.0
MAX_DEMAND_KW = 220.0
MIN_DEMAND_KW = 90.0

# Each phase contains 20 readings.
NORMAL_READINGS = 20
RISING_READINGS = 20
PEAK_READINGS = 20
RECOVERY_READINGS = 20

CYCLE_LENGTH = (
    NORMAL_READINGS
    + RISING_READINGS
    + PEAK_READINGS
    + RECOVERY_READINGS
)

MAX_CHANGE_PER_READING = 6.0


def get_latest_valid_reading(
    building_id: int,
    existing_readings: list[dict[str, Any]]
) -> dict[str, Any] | None:

    building_readings = []

    for reading in existing_readings:
        try:
            if int(reading["buildingId"]) != building_id:
                continue

            if str(
                reading.get("dataQualityStatus", "")
            ).upper() != "VALID":
                continue

            demand = Decimal(str(reading["demandKw"]))

            if not demand.is_finite():
                continue

            reading_id = int(reading.get("readingId", 0))

            building_readings.append(
                (reading_id, reading)
            )

        except (KeyError, TypeError, ValueError, InvalidOperation):
            continue

    if not building_readings:
        return None

    return max(
        building_readings,
        key=lambda item: item[0]
    )[1]


def get_simulator_reading_count(
    building_id: int,
    existing_readings: list[dict[str, Any]]
) -> int:
    """
    Counts valid readings generated by this simulator.
    Used to continue the simulation cycle across runs.
    """

    total = 0

    for reading in existing_readings:
        try:
            if int(reading["buildingId"]) != building_id:
                continue

            if str(
                reading.get("dataQualityStatus", "")
            ).upper() != "VALID":
                continue

            if str(
                reading.get("sourceName", "")
            ).strip().lower() != SIMULATOR_SOURCE_NAME.strip().lower():
                continue

            total += 1

        except (KeyError, TypeError, ValueError):
            continue

    return total


def get_target_demand(
    cycle_position: int,
    base_kw: float
) -> tuple[float, str]:

    if cycle_position < NORMAL_READINGS:
        return base_kw, "NORMAL"

    if cycle_position < NORMAL_READINGS + RISING_READINGS:
        progress = (
            cycle_position - NORMAL_READINGS + 1
        ) / RISING_READINGS

        target = (
            base_kw
            + (PEAK_TARGET_KW - base_kw) * progress
        )

        return target, "RISING"

    if cycle_position < (
        NORMAL_READINGS
        + RISING_READINGS
        + PEAK_READINGS
    ):
        return PEAK_TARGET_KW, "PEAK"

    progress = (
        cycle_position
        - NORMAL_READINGS
        - RISING_READINGS
        - PEAK_READINGS
        + 1
    ) / RECOVERY_READINGS

    target = (
        PEAK_TARGET_KW
        + (base_kw - PEAK_TARGET_KW) * progress
    )

    return target, "RECOVERY"


def generate_readings(
    building: dict[str, Any],
    existing_readings: list[dict[str, Any]],
    count: int = READINGS_PER_BUILDING
) -> list[dict[str, Any]]:

    building_id = int(building["buildingId"])

    if count <= 0:
        return []

    base_kw = float(
        Decimal("110")
        + Decimal(str((building_id * 13) % 21))
    )

    latest_reading = get_latest_valid_reading(
        building_id,
        existing_readings
    )

    if latest_reading:
        current_demand = float(
            latest_reading["demandKw"]
        )

        print(
            f"Building {building_id}: Continuing from "
            f"reading ID {latest_reading.get('readingId')} "
            f"with demand {current_demand:.2f} kW",
            flush=True
        )

    else:
        current_demand = base_kw

        print(
            f"Building {building_id}: Starting at "
            f"base demand {current_demand:.2f} kW",
            flush=True
        )

    simulator_count = get_simulator_reading_count(
        building_id,
        existing_readings
    )

    # Preserve existing IST timestamp behaviour.
    start_time = (
        datetime.now(INDIA_TIMEZONE)
        .replace(second=0, microsecond=0)
        - timedelta(minutes=count - 1)
    )

    readings = []
    phases_seen = set()

    for index in range(count):

        cycle_position = (
            simulator_count + index
        ) % CYCLE_LENGTH

        target_demand, phase = get_target_demand(
            cycle_position,
            base_kw
        )

        phases_seen.add(phase)

        # Gradually move towards the phase target.
        difference = target_demand - current_demand

        adjustment = max(
            -MAX_CHANGE_PER_READING,
            min(difference, MAX_CHANGE_PER_READING)
        )

        # Small random variation for realistic readings.
        noise = random.uniform(-1.2, 1.2)

        current_demand += adjustment + noise

        current_demand = max(
            MIN_DEMAND_KW,
            min(current_demand, MAX_DEMAND_KW)
        )

        demand = Decimal(
            str(current_demand)
        ).quantize(Decimal("0.01"))

        timestamp = start_time + timedelta(minutes=index)

        readings.append({
            "buildingId": building_id,
            "readingTimestamp": timestamp.strftime(
                "%Y-%m-%dT%H:%M:%S"
            ),
            "demandKw": str(demand),
            "sourceName": SIMULATOR_SOURCE_NAME,
            "dataQualityStatus": "VALID"
        })

    print(
        f"Building {building_id}: Generated {len(readings)} "
        f"readings. Phase(s): {', '.join(sorted(phases_seen))}. "
        f"Final demand: {current_demand:.2f} kW",
        flush=True
    )

    return readings
